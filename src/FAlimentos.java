    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        int ren = TConsultas.getSelectedRow();
       DefaultTableModel modelo = (DefaultTableModel) TConsultas.getModel();
       if (ren >=0){
           TClave.setText(modelo.getValueAt(ren, 0).toString());
           TTitulo.setText(modelo.getValueAt(ren, 1).toString());
           descripcion.setText(modelo.getValueAt(ren, 2).toString());
           precio.setText(modelo.getValueAt(ren, 3).toString());
           cartel = new ImageIcon(cnx.escalarImagen(((ImageIcon)modelo.getValueAt(ren, 4)).getImage(), 194,235));
           categoria.setText(modelo.getValueAt(ren, 5).toString());
           estado.setText(modelo.getValueAt(ren, 6).toString());
           LCartel.setIcon(cartel);
           
       }
    }//GEN-LAST:event_TConsultasMousePressed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
       JFileChooser fc = new JFileChooser(System.getProperty("user.dir")); 
        if(fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION){
                File archivo = fc.getSelectedFile();
                cartel = new ImageIcon(archivo.getPath()); //c:documento
                LCartel.setIcon(new ImageIcon(cnx.escalarImagen(cartel.getImage(), 194, 235)));
            
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String cla = TClave.getText();
        String tit = TTitulo.getText();
        String des = descripcion.getText();
        String pre = precio.getText();
        ImageIcon car = cartel;
        String cat = categoria.getText();
        String est = estado.getText();
        
        FAMenu menu = new FAMenu(cla, tit, des, pre, car, cat, est);
        if (menu.insertar(cnx)== 1){
            cnx.entablar("SELECT * FROM alimentos", TConsultas,  8, 20, 25, 10, 20, 10, 7);
        }else{
            JOptionPane.showMessageDialog(this, "no se pudo registrar la pelicula");
        }
        TClave.setText("");
        TTitulo.setText("");
        descripcion.setText("");
        precio.setText("");
        LCartel.setIcon(null);
        if (cartel == null) {
    JOptionPane.showMessageDialog(this, "Selecciona una imagen primero");
    return;
}
        categoria.setText("");
        estado.setText("");
                
    }//GEN-LAST:event_jButton1ActionPerformed

