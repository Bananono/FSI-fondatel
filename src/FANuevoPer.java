    public void guardar(){
         String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String nip = new String(txtNip.getPassword()).trim();

        if (codigo.isEmpty() || nombre.isEmpty() || usuario.isEmpty() || nip.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llena todos los campos.");
            return;
        }

        Empleados emp = new Empleados(codigo, nombre,
                cboPuesto.getSelectedItem().toString(),
                cboTurno.getSelectedItem().toString(),
                usuario, nip, "Activo");

        if (emp.insertar(cnx.con) > 0) {
            JOptionPane.showMessageDialog(this, "Empleado " + codigo + " agregado.");
            txtCodigo.setText(""); txtNombre.setText("");
            txtUsuario.setText(""); txtNip.setText("");
            cnx.entablar(consulta, tabla);
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo guardar. ¿El código ya existe?");
        }
    }
    



